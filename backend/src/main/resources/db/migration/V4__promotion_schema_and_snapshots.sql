BEGIN
    IF EXISTS (
        SELECT 1 FROM orders
        WHERE total_price < 0 OR COALESCE(shipping_fee, 0) < 0
           OR total_price < COALESCE(shipping_fee, 0)
    ) THEN
        RAISE EXCEPTION 'Promotion migration requires review of invalid historical order totals/shipping fees';
    END IF;
END $$;

