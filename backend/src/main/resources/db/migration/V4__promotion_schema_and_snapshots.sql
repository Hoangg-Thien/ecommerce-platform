CREATE TABLE promotion_programs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    start_date TIMESTAMPTZ NOT NULL,
    end_date TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT chk_program_dates CHECK (end_date > start_date),
    CONSTRAINT chk_program_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promotion_program_id BIGINT NOT NULL REFERENCES promotion_programs(id),
    code VARCHAR(50) NOT NULL,
    discount_percent NUMERIC(5,2) NOT NULL,
    minimum_amount NUMERIC(15,2) NOT NULL DEFAULT 0,
    maximum_discount NUMERIC(15,2),
    quantity INTEGER NOT NULL,
    used_quantity INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT uq_vouchers_code UNIQUE (code),
    CONSTRAINT chk_voucher_code CHECK (code ~ '^[A-Z0-9_-]+$'),
    CONSTRAINT chk_voucher_percent CHECK (discount_percent > 0 AND discount_percent <= 100),
    CONSTRAINT chk_voucher_min CHECK (minimum_amount >= 0),
    CONSTRAINT chk_voucher_max CHECK (maximum_discount IS NULL OR maximum_discount > 0),
    CONSTRAINT chk_voucher_qty CHECK (quantity > 0 AND used_quantity >= 0 AND used_quantity <= quantity),
    CONSTRAINT chk_voucher_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE INDEX idx_vouchers_program ON vouchers(promotion_program_id);

CREATE TABLE order_discounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promotion_program_id BIGINT NOT NULL REFERENCES promotion_programs(id),
    minimum_amount NUMERIC(15,2) NOT NULL,
    discount_percent NUMERIC(5,2) NOT NULL,
    maximum_discount NUMERIC(15,2),
    CONSTRAINT uq_order_discount_tier UNIQUE (promotion_program_id, minimum_amount),
    CONSTRAINT chk_order_discount_pct CHECK (discount_percent > 0 AND discount_percent <= 100),
    CONSTRAINT chk_order_discount_min CHECK (minimum_amount >= 0),
    CONSTRAINT chk_order_discount_max CHECK (maximum_discount IS NULL OR maximum_discount > 0)
);

CREATE TABLE product_discounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promotion_program_id BIGINT NOT NULL REFERENCES promotion_programs(id),
    -- Deleting an unused product removes its rule, never its program or order snapshots.
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    discount_percent NUMERIC(5,2) NOT NULL,
    CONSTRAINT uq_product_discount_program_product UNIQUE (promotion_program_id, product_id),
    CONSTRAINT chk_product_discount_pct CHECK (discount_percent > 0 AND discount_percent <= 100)
);
CREATE INDEX idx_product_discounts_product ON product_discounts(product_id);

CREATE TABLE voucher_usages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id BIGINT NOT NULL REFERENCES vouchers(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    order_id BIGINT NOT NULL REFERENCES orders(id),
    discount_amount NUMERIC(15,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'APPLIED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    released_at TIMESTAMPTZ,
    CONSTRAINT uq_voucher_usages_order UNIQUE (order_id),
    CONSTRAINT chk_usage_status CHECK (status IN ('APPLIED', 'RELEASED')),
    CONSTRAINT chk_usage_discount CHECK (discount_amount >= 0)
);
CREATE UNIQUE INDEX uq_voucher_usage_active_per_user
    ON voucher_usages(voucher_id, user_id) WHERE status = 'APPLIED';
CREATE INDEX idx_voucher_usages_user ON voucher_usages(user_id);

